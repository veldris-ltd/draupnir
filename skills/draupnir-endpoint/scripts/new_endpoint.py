def _path_arguments(path: str) -> tuple[str, str, str, str]:
    """Return (signature lines, `del` suffix, subject expression, detail placeholder)."""
    names = PATH_PARAM.findall(path)
    if not names:
        return "", "", '"singleton"', "the collection"
    lines = "".join(
        PATH_ANNOTATION.format(name=name, readable=name.replace("_", " ")) for name in names
    )
    first = names[0]
    # The detail is substituted into an f-string in the template, so it stays a
    # placeholder rather than becoming one: `str.format` does not re-scan what
    # it substituted, which is what lets a `{name}` survive into the output.
    return "\n" + lines.rstrip("\n"), ", " + ", ".join(names), first, "{" + first + "}"


def _concrete(path: str) -> str:
    """`/corpora/{iso3}/retention` -> `/v1/corpora/GBR/retention`, for a request."""
    return "/v1" + PATH_PARAM.sub("sample", path)


#: Which role satisfies each permission, from SAD 9.4's grant table. The
#: generated test needs one to send, and picking it from the table rather than
#: guessing is why the test asserts something.
ROLE_FOR: Final[dict[str, str]] = {
    "READ": "viewer",
    "REGISTER_SOURCE": "curator",
    "CURATE": "curator",
    "SUBMIT_RUN": "operator",
    "CANCEL_RUN": "operator",
    "DECIDE_GATE": "approver",
    "PUBLISH_RELEASE": "approver",
    "MANAGE_USERS": "admin",
    "MANAGE_PLUGINS": "admin",
    "MANAGE_POLICY": "admin",
}


def _register(app_py: Path, module: str) -> bool:
    """Add the router to `create_app`, in the order the file already uses."""
    text = app_py.read_text(encoding="utf-8")
    line = f"    v1.include_router({module}.router)\n"
    if line in text:
        return False

    anchor = "    app.include_router(v1)\n"
    if anchor not in text:
        msg = (
            "draupnir/api/app.py has no `app.include_router(v1)` line to insert before. "
            "Register the router by hand, or pass --no-register."
        )
        raise ScaffoldError(msg)
    text = text.replace(anchor, line + anchor, 1)

    imported = "from draupnir.api.routers import (\n"
    if imported in text:
        start = text.index(imported) + len(imported)
        end = text.index(")\n", start)
        names = sorted({*[item.strip().rstrip(",") for item in text[start:end].split()], module})
        text = text[:start] + "".join(f"    {name},\n" for name in names) + text[end:]
    else:
        msg = (
            "draupnir/api/app.py does not import its routers as a parenthesised group, "
            "so this scaffold cannot add to it. Add the import by hand."
        )
        raise ScaffoldError(msg)

    app_py.write_text(text, encoding="utf-8", newline="\n")
    return True


def scaffold(
    *,
    router: str,
    shape: str,
    path: str,
    operation_id: str,
    summary: str,
    permission: str,
    model: str | None = None,
    tag: str | None = None,
    out: Path,
    tests_out: Path,
    app_py: Path | None = None,
) -> list[Path]:
    """Write the router and its surface checks, returning every path written."""
    if shape not in SHAPES:
        msg = f"{shape!r} is not a shape. One of: {', '.join(SHAPES)}."
        raise ScaffoldError(msg)
    if not MODULE.match(router):
        msg = f"{router!r} is not a module name. Lowercase, underscores, e.g. `retention`."
        raise ScaffoldError(msg)
    if not OPERATION_ID.match(operation_id):
        msg = (
            f"{operation_id!r} is not an operation id. It is lowerCamelCase, because it "
            "becomes the generated CLI command's name and the TypeScript operation's "
            "key, e.g. `listRetention`."
        )
        raise ScaffoldError(msg)
    if not PATH.match(path):
        msg = (
            f"{path!r} is not a path. Leading slash, lowercase segments, `{{name}}` for a "
            "parameter, and no `/v1` prefix -- `create_app` mounts every router under it."
        )
        raise ScaffoldError(msg)
    if path.startswith(("/v1/", "/v1")) and path.split("/")[1] == "v1":
        msg = (
            f"{path!r} carries the version. `create_app` mounts every router under one "
            '`APIRouter(prefix="/v1")`, so a router that adds its own answers '
            "`/v1/v1/...` and the generated clients call a path that does not exist."
        )
        raise ScaffoldError(msg)
    if permission not in PERMISSIONS:
        msg = f"{permission!r} is not a permission. SAD 9.4 names ten: {', '.join(PERMISSIONS)}."
        raise ScaffoldError(msg)
    if shape == "item" and not PATH_PARAM.search(path):
        msg = (
            "an `item` shape reads one resource, so its path needs a parameter, e.g. "
            "`/retention/{corpus_id}`. Use `collection` for a list."
        )
        raise ScaffoldError(msg)

    model = model or "".join(part.capitalize() for part in router.split("_"))
    tag = tag or router.replace("_", "-")
    function = snake(operation_id)
    role = ROLE_FOR[permission]
    path_args, path_deletes, subject, detail = _path_arguments(path)
    imports = IMPORTS[shape]
    if path_args:
        imports = "from typing import Annotated\n\n" + imports.replace(
            "from fastapi import APIRouter", "from fastapi import APIRouter, Path"
        )

    body = HEADER.format(summary=summary, imports=imports, tag=tag)
    if shape == "collection":
        body += MODELS_COLLECTION.format(model=model)
        body += COLLECTION.format(
            path=path,
            summary=summary,
            operation_id=operation_id,
            model=model,
            permission=permission,
            function=function,
            tag=tag,
            path_args=path_args,
            path_deletes=path_deletes,
            read_note=READ_NOTE,
        )
        extra_tests = COLLECTION_TESTS.format(path=path)
        verb = "get"
    elif shape == "item":
        body += MODELS_ITEM.format(model=model)
        body += ITEM.format(
            path=path,
            summary=summary,
            operation_id=operation_id,
            model=model,
            permission=permission,
            function=function,
            tag=tag,
            code=tag,
            path_args=path_args,
            detail_expression=detail,
            read_note=READ_NOTE,
        )
        extra_tests = ""
        verb = "get"
    else:
        body += MODELS_MUTATION.format(model=model)
        names = PATH_PARAM.findall(path)
        body += MUTATION.format(
            path=path,
            summary=summary,
            operation_id=operation_id,
            model=model,
            permission=permission,
            function=function,
            tag=tag,
            path_args=path_args,
            payload_entries="".join(f'"{name}": {name}, ' for name in names),
            subject_expression=subject,
        )
        extra_tests = MUTATION_TESTS.format(role=role, concrete_path=_concrete(path))
        verb = "post"

    out.mkdir(parents=True, exist_ok=True)
    tests_out.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []

    def write(target: Path, text: str) -> None:
        target.write_text(text, encoding="utf-8", newline="\n")
        written.append(target)

    write(out / f"{router}.py", body)
    write(
        tests_out / f"test_{router}_endpoint.py",
        TEST_TEMPLATE.format(
            operation_id=operation_id,
            module=router,
            path=path,
            concrete_path=_concrete(path),
            verb=verb,
            role=role,
            extra_tests=extra_tests,
        ),
    )

    if app_py is not None and _register(app_py, router):
        written.append(app_py)

    return written


def main(argv: list[str] | None = None) -> int:
    """Scaffold an operation from the command line."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--router", required=True, help="module name, e.g. retention")
    parser.add_argument("--shape", required=True, choices=SHAPES)
    parser.add_argument("--path", required=True, help="e.g. /retention/{corpus_id}, no /v1")
    parser.add_argument("--operation-id", required=True, help="lowerCamelCase, e.g. listRetention")
    parser.add_argument("--summary", required=True)
    parser.add_argument("--permission", required=True, choices=PERMISSIONS)
    parser.add_argument("--model", help="wire model prefix; defaults from --router")
    parser.add_argument("--tag", help="OpenAPI tag; defaults from --router")
    parser.add_argument("--out", type=Path, default=REPO_ROOT / "draupnir" / "api" / "routers")
    parser.add_argument("--tests-out", type=Path, default=REPO_ROOT / "tests" / "contract")
    parser.add_argument(
        "--no-register",
        action="store_false",
        dest="register",
        help="do not add the router to create_app (for scaffolding outside the repo)",
    )
    args = parser.parse_args(argv)

    try:
        written = scaffold(
            router=args.router,
            shape=args.shape,
            path=args.path,
            operation_id=args.operation_id,
            summary=args.summary,
            permission=args.permission,
            model=args.model,
            tag=args.tag,
            out=args.out,
            tests_out=args.tests_out,
            app_py=(REPO_ROOT / "draupnir" / "api" / "app.py") if args.register else None,
        )
    except ScaffoldError as error:
        parser.error(str(error))

    for path in written:
        print(f"wrote {path}")

    if args.shape != "mutation":
        # The read the handler needs, spelled out. It is not generated, because
        # `ReadModel` is a Protocol with two implementations and a scaffold that
        # edited all three would be editing the one file where a mistake is a
        # site-scoping mistake.
        model = args.model or "".join(part.capitalize() for part in args.router.split("_"))
        returns = f"{model}Page" if args.shape == "collection" else f"{model}Out"
        extra = ", limit: int, cursor: str | None" if args.shape == "collection" else ""
        signature = f"    async def {snake(args.operation_id)}(self, site_id: str{extra})"
        print(
            "\nAdd this to the `ReadModel` Protocol in draupnir/api/reading.py, and to "
            "both `EmptyReadModel` and `DatabaseReadModel`:\n\n"
            f"{signature} -> {returns}: ...\n"
            "\nRead through `_scoped()`. Row-level security shows zero rows to a session "
            "that has not set draupnir.site_id (AC-B10, AC-F18)."
        )

    print("\nNext: `make openapi && make clients && make test-contract`.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
