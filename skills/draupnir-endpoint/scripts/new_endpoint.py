MODELS_MUTATION = '''

class {model}In(Wire):
    """What the caller sends.

    `extra="forbid"` comes from `Wire`, so a misspelled field is a 422 with a
    problem document rather than a silently ignored value.
    """

    reason: str = Field(description="Why this is being done. Recorded in the ledger.")
'''

READ_NOTE = """
    # The read model has no method for this yet, and an endpoint that invented
    # rows would be worse than one that returns none: `EmptyReadModel` is what
    # a contract test runs against, and answering nothing is its honest answer.
    #
    # To make this return something, add the method to the `ReadModel` Protocol
    # in `draupnir/api/reading.py` and to both implementations. Read through
    # `_scoped()`: row-level security shows zero rows to a session that has not
    # set `draupnir.site_id`, so site scoping is enforced by the database
    # rather than by remembering a WHERE clause (AC-B10, AC-F18).
"""

COLLECTION = '''

@router.get(
    "{path}",
    summary="{summary}",
    operation_id="{operation_id}",
    response_model={model}Page,
)
@needs(Permission.{permission})
async def {function}(
    ctx: Guarded,
    reading: Reading,
    limit: PageSize,
    cursor: Cursor = None,{path_args}
) -> {model}Page:
    """{summary}."""
    del ctx, reading, cursor{path_deletes}
{read_note}
    page = {model}Page(items=[], meta=PageMeta(next_cursor=None, limit=limit))
    telemetry.log("{tag}.listed", count=len(page.items))
    return page
'''

ITEM = '''

@router.get(
    "{path}",
    summary="{summary}",
    operation_id="{operation_id}",
    response_model={model}Out,
)
@needs(Permission.{permission})
async def {function}(
    ctx: Guarded,
    reading: Reading,{path_args}
) -> {model}Out:
    """{summary}.

    A resource that is not there is a problem document with a stable type URI,
    not a bare 404 and never an `HTTPException` (AC-B2).
    """
    del ctx, reading
{read_note}
    raise ProblemError(
        status=404,
        code="{code}-not-found",
        title="Not found",
        detail=f"no {tag} {detail_expression}",
    )
'''

MUTATION = '''

@router.post(
    "{path}",
    summary="{summary}",
    operation_id="{operation_id}",
    status_code=status.HTTP_202_ACCEPTED,
    response_model=Accepted,
)
@needs(Permission.{permission})
async def {function}(
    body: {model}In,
    ctx: Guarded,{path_args}
    if_match: IfMatch = None,
    idempotency_key: IdempotencyKey = None,
) -> Accepted:
    """{summary}.

    Returns 202. Nothing blocks an HTTP request on work that takes minutes
    (AC-B9); the caller gets a run identifier and watches the event stream.
    """
    key = require_idempotency_key(idempotency_key)
    payload = {{{payload_entries}**body.model_dump(mode="json")}}

    # A replay returns what the first request returned, rather than acting
    # twice (AC-B1). This is before any work, because a replay must not do any.
    replayed = replay_or_reserve(key, ctx, payload)
    if replayed is not None and replayed.body:
        return Accepted.model_validate(replayed.body)

    try:
        require("{tag}", {{"id": {subject_expression}}}, if_match)
    except ConcurrencyError as error:
        # The reservation is released, or the key is burnt on a request that
        # never acted and the caller can never retry it.
        release(key, ctx)
        raise as_problem(error) from error

    run_id = new_id()
    with telemetry.span("{tag}.{function}", telemetry.EDGE, runId=str(run_id)):
        telemetry.log("{tag}.accepted", runId=str(run_id))

    result = accepted(run_id, detail="{summary}")
    complete(key, ctx, status=status.HTTP_202_ACCEPTED, body=result)
    return Accepted.model_validate(result)
'''

