"""Scaffold a DRAUPNIR API operation with the conventions of SAD 11E.2 applied.

The output starts the application, generates both clients and passes the API
surface contract with no manual edit. `tests/contract/test_skills.py` mounts it
on a real application and drives it, which is the test of whether this skill is
real.

Three shapes, because the shape is the decision that matters: a collection is
cursor paginated and never offset; an item answers 404 as a problem document;
a mutation requires an `Idempotency-Key` and returns 202 rather than holding a
connection open.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path
from typing import Final

REPO_ROOT = Path(__file__).resolve().parents[3]

#: SAD 9.4's vocabulary, as `draupnir.svalinn.roles.Permission` spells it. A
#: name not in this list is a typo, and a typo here is a route that starts and
#: guards nothing recognisable.
PERMISSIONS: Final = (
    "READ",
    "REGISTER_SOURCE",
    "CURATE",
    "SUBMIT_RUN",
    "CANCEL_RUN",
    "DECIDE_GATE",
    "PUBLISH_RELEASE",
    "MANAGE_USERS",
    "MANAGE_PLUGINS",
    "MANAGE_POLICY",
)

SHAPES: Final = ("collection", "item", "mutation")

#: `listRetention`, `getRunLineage`. It is the generated CLI command's name and
#: the generated TypeScript operation's key, so it is lowerCamelCase and stable.
OPERATION_ID = re.compile(r"^[a-z][a-zA-Z0-9]*$")

#: `/retention`, `/corpora/{iso3}/retention`. Leading slash, no trailing one,
#: no version prefix -- `create_app` mounts every router under `/v1`.
PATH = re.compile(r"^(?:/(?:[a-z][a-z0-9-]*|\{[a-z_][a-z0-9_]*\}))+$")

MODULE = re.compile(r"^[a-z][a-z0-9_]*$")

PATH_PARAM = re.compile(r"\{([a-z_][a-z0-9_]*)\}")


class ScaffoldError(ValueError):
    """The arguments would produce an operation that cannot be registered."""


def snake(camel: str) -> str:
    """`listRetention` -> `list_retention`."""
    return re.sub(r"(?<!^)(?=[A-Z])", "_", camel).lower()


