"""Scaffold a JARNGREIPR component: seven states, tokens only, named by role.

The output passes the token linter, `stories.test.ts` and an axe run in jsdom
with no manual edit. That is the test of whether this skill is real, and
`tests/contract/test_skills.py` regenerates the worked example and compares it
byte for byte with what is committed.

Three things are generated rather than described, because all three are what a
component author gets wrong under time pressure: the seven state stories, the
`StateSurface` delegation, and a stylesheet that reaches for a hex value only
by never having one in it.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path
from typing import Final

REPO_ROOT = Path(__file__).resolve().parents[3]
SRC = REPO_ROOT / "web" / "packages" / "jarngreipr" / "src"

#: `primitives` are the sixteen generic controls, `composites` the eight
#: DRAUPNIR-shaped assemblies, and `example` is where this skill's worked
#: example lives -- inside the package so the token linter, `tsc`, Storybook
#: and Vitest all see it, and out of `index.ts` so it is not public API.
LAYERS: Final = ("primitives", "composites", "example")

NAME = re.compile(r"^[A-Z][A-Za-z0-9]*$")

#: The seven story exports Storybook's static indexer will find, in story
#: order. `stories.test.ts` asserts exactly this list.
STORY_EXPORTS: Final = (
    "Ready",
    "Loading",
    "Empty",
    "ErrorState",
    "Denied",
    "ReadOnly",
    "Partitioned",
)


class ComponentError(ValueError):
    """The arguments would produce a component that cannot pass the gates."""


def kebab(name: str) -> str:
    """`PoolStatus` -> `pool-status`, for the CSS class prefix."""
    return re.sub(r"(?<!^)(?=[A-Z])", "-", name).lower()


COMPONENT = """\
import type {{ JSX }} from 'react';
import {{ StateSurface, type StateProps }} from '{states}';
import './{name}.css';

/** One row of {summary_lower} */
export interface {name}Item {{
  /** Stable identifier. Used as the React key, so it must not be an index. */
  id: string;
  /** What this row is called, in the operator's words rather than the schema's. */
  label: string;
  /**
   * The value, already formatted. Formatting here would mean a locale decision
   * inside a design system, and the caller is the one that knows the locale.
   */
  value: string;
  /**
   * How the value reads. Carried as a word as well as a colour, because a
   * status that is only a colour is a status a third of readers cannot see
   * (WCAG 1.4.1).
   */
  tone?: 'neutral' | 'info' | 'success' | 'warning' | 'danger' | undefined;
}}

export interface {name}Props extends StateProps {{
  /** What this component is, for its accessible name. */
  label: string;
  /** The rows. An empty array is not the `empty` state -- the caller says so. */
  items: {name}Item[];
}}

/**
 * {summary}
 *
 * Generated by `skills/jarngreipr-component`.
 *
 * The five replacing states are delegated to `StateSurface` rather than
 * implemented here. That is the whole reason the state layer sits under the
 * components: a component that renders its own "no permission" panel renders a
 * slightly different one, and by the twentieth component `denied` means five
 * things. Here it means one.
 *
 * `readOnly` is not delegated, because it does not replace the content: the
 * rows stay visible and the controls go inert, so the shape of what exists is
 * still legible to someone who cannot change it.
 */
export function {name}({{
  label,
  items,
  state = 'ready',
  stateMessage,
  problem,
}}: {name}Props): JSX.Element {{
  const inert = state === 'readOnly';

  return (
    <div className="jg-{slug}" data-jg-state={{state}}>
      <StateSurface
        state={{state}}
        stateMessage={{stateMessage}}
        problem={{problem}}
        label={{label}}
        minHeight="6rem"
      >
        <h3 className="jg-{slug}__label">{{label}}</h3>
        <ul className="jg-{slug}__list" aria-label={{label}}>
          {{items.map((item) => (
            <li className="jg-{slug}__row" key={{item.id}} data-jg-tone={{item.tone ?? 'neutral'}}>
              <span className="jg-{slug}__name">{{item.label}}</span>
              <span className="jg-{slug}__value">{{item.value}}</span>
            </li>
          ))}}
        </ul>
        {{inert ? (
          <p className="jg-{slug}__note">Read only. You may see this and not change it.</p>
        ) : null}}
      </StateSurface>
    </div>
  );
}}
"""

