STORIES = """\
import type {{ Meta }} from '@storybook/react';
import {{ COMPONENT_META, SAMPLE_PROBLEM, stateStories }} from '{stories_module}';
import {{ {name} }} from './{name}';

// A literal, because Storybook's story indexer is static: a default export it
// cannot read at parse time is a component that never appears in the sidebar.
export default {{
  title: '{title}/{name}',
  ...COMPONENT_META,
}} satisfies Meta;

const SAMPLE = [
  {{ id: 'adapters', label: 'adapters', value: '18 / 24', tone: 'warning' }},
  {{ id: 'merges', label: 'merges', value: '2 / 8', tone: 'success' }},
  {{ id: 'export', label: 'export', value: '0 / 4', tone: 'neutral' }},
] as const;

const stories = stateStories((state) => (
  <{name} label="{label}" items={{[...SAMPLE]}} state={{state}} problem={{SAMPLE_PROBLEM}} />
));

{exports}"""


def _relative(layer: str) -> tuple[str, str, str]:
    """Return the import paths and the Storybook title for `layer`."""
    return "../state/states", "../state/stories", layer.capitalize()


def scaffold(
    *,
    name: str,
    layer: str,
    summary: str,
    src: Path = SRC,
    label: str | None = None,
) -> list[Path]:
    """Write the component, its stylesheet and its stories."""
    if not NAME.match(name):
        msg = (
            f"{name!r} is not a component name. PascalCase, e.g. `PoolStatus`: it is "
            "the exported symbol, the story file's stem and the Storybook title."
        )
        raise ComponentError(msg)
    if layer not in LAYERS:
        msg = f"{layer!r} is not a layer. One of: {', '.join(LAYERS)}."
        raise ComponentError(msg)
    if not summary.endswith("."):
        msg = "the summary is the component's docstring first line; end it with a full stop."
        raise ComponentError(msg)

    states, stories_module, title = _relative(layer)
    slug = kebab(name)
    directory = src / layer
    directory.mkdir(parents=True, exist_ok=True)

    written: list[Path] = []

    def write(target: Path, text: str) -> None:
        target.write_text(text, encoding="utf-8", newline="\n")
        written.append(target)

    write(
        directory / f"{name}.tsx",
        COMPONENT.format(
            name=name,
            slug=slug,
            states=states,
            summary=summary,
            summary_lower=summary[0].lower() + summary[1:],
        ),
    )
    write(directory / f"{name}.css", STYLES.format(name=name, slug=slug))
    write(
        directory / f"{name}.stories.tsx",
        STORIES.format(
            name=name,
            stories_module=stories_module,
            title=title,
            label=label or summary.rstrip("."),
            exports="\n".join(
                f"export const {export} = stories.{export};" for export in STORY_EXPORTS
            )
            + "\n",
        ),
    )

    if layer != "example":
        written.extend(_register(src, layer, name))

    return written


def _register(src: Path, layer: str, name: str) -> list[Path]:
    """Export the component from its layer barrel and from the package barrel.

    `stories.test.ts` reads `index.ts`'s `export { ... } from './<layer>'`
    block to decide which components must have seven stories. A component
    missing from it ships whatever stories it happens to have, and nothing
    fails -- which is the hole this closes.
    """
    changed: list[Path] = []

    barrel = src / layer / "index.tsx"
    text = barrel.read_text(encoding="utf-8")
    line = f"export * from './{name}';\n"
    if line not in text:
        text = text.rstrip("\n") + "\n\n" + line
        barrel.write_text(text, encoding="utf-8", newline="\n")
        changed.append(barrel)

    package = src / "index.ts"
    source = package.read_text(encoding="utf-8")
    updated = _insert_export(source, layer, name, values=True)
    updated = _insert_export(updated, layer, f"{name}Props", values=False)
    if updated != source:
        package.write_text(updated, encoding="utf-8", newline="\n")
        changed.append(package)

    return changed


def _insert_export(source: str, layer: str, symbol: str, *, values: bool) -> str:
    """Add `symbol` to the sorted export block for `layer`, if not already there."""
    keyword = "export {" if values else "export type {"
    pattern = re.compile(
        rf"{re.escape(keyword)}\n(?P<body>(?:^  .*\n)+)}} from '\./{layer}';",
        re.MULTILINE,
    )
    match = pattern.search(source)
    if match is None:
        kind = "value" if values else "type"
        msg = (
            f"web/packages/jarngreipr/src/index.ts has no sorted {kind} export block for "
            f"./{layer}. Add the export by hand."
        )
        raise ComponentError(msg)

    entries = [line.strip().rstrip(",") for line in match.group("body").splitlines()]
    if symbol in entries:
        return source
    merged = sorted([*entries, symbol])
    body = "".join(f"  {entry},\n" for entry in merged)
    return source[: match.start("body")] + body + source[match.end("body") :]


def main(argv: list[str] | None = None) -> int:
    """Scaffold a component from the command line."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--name", required=True, help="PascalCase, e.g. PoolStatus")
    parser.add_argument("--layer", required=True, choices=LAYERS)
    parser.add_argument("--summary", required=True, help="the docstring's first line")
    parser.add_argument("--label", help="the story's accessible name; defaults to the summary")
    parser.add_argument("--src", type=Path, default=SRC)
    args = parser.parse_args(argv)

    try:
        written = scaffold(
            name=args.name,
            layer=args.layer,
            summary=args.summary,
            src=args.src,
            label=args.label,
        )
    except ComponentError as error:
        parser.error(str(error))

    for path in written:
        print(f"wrote {path}")
    print(
        "\nNext: `pnpm lint:tokens`, `pnpm test` and `pnpm --filter @draupnir/jarngreipr "
        "typecheck`. Then write the component's actual content in place of the rows."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
