"""Scaffold a conforming DRAUPNIR plug-in driver.

The output passes `check_job_driver` with no manual edit. That is the test of
whether this skill is real, and `tests/contract/test_skills.py` runs it.

Everything the generated driver does is a consequence of one rule: `render` is
pure (SAD Decision S5). It is why there is no `os`, no `datetime`, no network
client and no file write anywhere in the rendered plan, and why the capability
set is declared once and consulted by `validate` rather than restated.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Final

REPO_ROOT = Path(__file__).resolve().parents[3]

#: The seven extension points of SAD 8.2, and the Protocol each takes.
GROUPS: Final[dict[str, str]] = {
    "draupnir.train": "TrainDriver",
    "draupnir.merge": "MergeDriver",
    "draupnir.eval": "EvalDriver",
    "draupnir.export": "ExportDriver",
    "draupnir.schedule": "ScheduleDriver",
    "draupnir.store": "StoreDriver",
    "draupnir.policy": "PolicyDriver",
}

#: The groups whose drivers plan and collect a job, and which `check_job_driver`
#: therefore covers. The other three have narrower interfaces of their own.
JOB_GROUPS: Final = frozenset(
    {"draupnir.train", "draupnir.merge", "draupnir.eval", "draupnir.export"}
)

#: `artefact_kind` in the database. A driver that invents a ninth value writes
#: a row the schema refuses, and it refuses it at collection time -- after the
#: allocation has been spent.
ARTEFACT_KINDS: Final = (
    "corpus_raw",
    "corpus_curated",
    "base_model",
    "substrate",
    "adapter",
    "merged",
    "quantised",
    "report",
)

#: `namespace.implementation/vMAJOR`, the same shape `InterfaceName` parses.
#: Checked here so a mistyped name is a scaffold error rather than a
#: conformance finding an hour later.
NAME_PATTERN: Final = re.compile(r"^[a-z0-9_]+\.[a-z0-9_]+/v[1-9][0-9]*$")

DISTRIBUTION_PATTERN: Final = re.compile(r"^[a-z][a-z0-9]*(-[a-z0-9]+)+$")


class ScaffoldError(ValueError):
    """The arguments would produce a driver that cannot conform."""


def module_of(distribution: str) -> str:
    """`veldris-draupnir-zip-export` -> `draupnir_zip_export`."""
    return distribution.removeprefix("veldris-").replace("-", "_")


def class_of(name: str) -> str:
    """`skidbladnir.zip/v1` -> `ZipDriver`."""
    local = name.split("/", 1)[0].split(".")[-1]
    return "".join(part.capitalize() for part in local.split("_")) + "Driver"


DRIVER_TEMPLATE = '''\
"""{summary}

Generated by `skills/draupnir-driver`. Two methods carry this driver's own
logic -- `validate` and `render` -- and the rest is the shape every driver in
this group shares.

`render` is pure, as SAD Decision S5 requires: it returns a command built from
the specification and nothing else. It opens no file, resolves no name and
takes no clock reading, because a plan that depends on any of those cannot be
reproduced from the specification that asked for it. The conformance suite
checks that by rendering twice, rendering again after a pause, rendering with
the network removed, and comparing the working directory before and after.
"""

from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass, field
from pathlib import Path

from draupnir.interfaces.types import (
    JobPlan,
    ProducedArtefact,
    ProgressEvent,
    ProgressKind,
    ResourceRequest,
    RunArtefacts,
    RunSpec,
    ValidationError,
)

NAME = "{name}"

#: The extension point this driver is loaded for. Named here so `validate` asks
#: the specification what *this* group requires, rather than reaching into
#: whichever block happens to hold it today.
GROUP = "{group}"

#: What this driver declares it can do. SAD 10.3 rule 4: the core refuses to
#: plan a job whose specification requires a capability not declared here, and
#: the refusal names the demand. Declared once, so `validate` consults it
#: rather than restating it.
CAPABILITIES = frozenset({{{capabilities}}})

#: What the job is expected to leave behind. Named here rather than inline so
#: `render` and `collect` cannot drift apart about it.
OUTPUT = "{output}"

#: The `artefact_kind` the output is recorded as. One of the eight the schema
#: knows; a ninth is refused at collection time, after the allocation is spent.
OUTPUT_KIND = "{artefact_kind}"

#: `step 10/100`, optionally followed by `loss=1.234`.
_STEP = re.compile(r"^step\\s+(?P<step>\\d+)\\s*/\\s*(?P<total>\\d+)")
_LOSS = re.compile(r"\\bloss\\s*=\\s*(?P<loss>-?\\d+(?:\\.\\d+)?)")


@dataclass
class {classname}:
    """{summary}"""

    name: str = NAME
    capabilities: frozenset[str] = CAPABILITIES
    #: Keeps the dataclass keyword-constructible without a mutable default
    #: leaking onto the class. The loader constructs a driver with no arguments.
    _: dict[str, str] = field(default_factory=dict, repr=False)

    # -- plan ---------------------------------------------------------------

    def validate(self, spec: RunSpec) -> list[ValidationError]:
        """Return every reason this driver cannot run `spec`.

        Returns rather than raises, and returns *all* of the problems: an
        operator correcting a specification needs one round trip, not five.
        """
        problems: list[ValidationError] = []

        unsupported = sorted(spec.capabilities_for(GROUP) - self.capabilities)
        if unsupported:
            declared = ", ".join(sorted(self.capabilities))
            problems.append(
                ValidationError(
                    field="spec",
                    message=(
                        f"{{NAME}} declares {{declared}}, and this specification "
                        f"requires {{', '.join(unsupported)}}"
                    ),
                    code="unsupported-capability",
                )
            )

        # Your own checks go here. Append to `problems`; never raise, and never
        # return early on the first one.

        return problems

    def render(self, spec: RunSpec, workdir: Path) -> JobPlan:
        """Return the exact command this job runs.

        Pure. Everything it uses comes from `spec`. `workdir` is where the job
        will run and is deliberately not read: reading it would make the plan a
        function of the machine that rendered it.
        """
        del workdir

        return JobPlan(
            command=(
                "{executable}",
                "--run",
                spec.metadata.name,
                "--base",
                spec.base.artefact,
                "--output",
                OUTPUT,
            ),
            environment={{"PYTHONHASHSEED": "0"}},
            workdir=".",
            resources=ResourceRequest(
                partition=spec.placement.partition,
                nodes=spec.placement.nodes,
                gpus_per_node={gpus},
            ),
            expected_artefacts=(OUTPUT,),
        )

    # -- observe ------------------------------------------------------------

    def parse_progress(self, line: str) -> ProgressEvent | None:
        """Translate one line of tool output into an event, or return None.

        Total and pure: any line at all, twice, the same answer, and `None` for
        a line that carries no event. It stamps no time, so replaying a
        captured log yields the events it yielded live.
        """
        match = _STEP.match(line.strip())
        if match is None:
            return None
        loss = _LOSS.search(line)
        return ProgressEvent(
            kind=ProgressKind.LOSS if loss else ProgressKind.STEP,
            step=int(match["step"]),
            total=int(match["total"]),
            value=float(loss["loss"]) if loss else None,
        )

    # -- collect ------------------------------------------------------------

    def collect(self, workdir: Path) -> RunArtefacts:
        """Return what the job produced, with digests. Reads; never writes."""
        produced = workdir / OUTPUT
        if not produced.is_file():
            # Absence is a finding for the caller, not a silence and not an
            # exception: the run is what failed, and collection is what says so.
            return RunArtefacts()

        return RunArtefacts(
            artefacts=(
                ProducedArtefact(
                    path=OUTPUT,
                    kind=OUTPUT_KIND,
                    sha256=_digest(produced),
                    size=produced.stat().st_size,
                ),
            )
        )


def _digest(path: Path, *, block: int = 1 << 20) -> str:
    """SHA-256 of a file, read in blocks so a large artefact never loads."""
    running = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(block), b""):
            running.update(chunk)
    return running.hexdigest()


#: What the entry point resolves to. The loader constructs nothing: it reads
#: this object, checks it against the Protocol and registers it.
driver = {classname}()

__all__ = ["CAPABILITIES", "NAME", "OUTPUT", "{classname}", "driver"]
'''

