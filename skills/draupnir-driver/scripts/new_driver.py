CONSTANTS_TEMPLATE = """
#: The `{block}` block of the SAD 6.2 sample. It asks for more than a freshly
#: scaffolded driver declares, so the conformance run narrows it to what this
#: driver actually offers rather than watching it refuse the example.
SAMPLE = SAMPLE_SPEC_MAPPING["spec"]["{block}"]
ACCEPTED = {{**SAMPLE, {accepted}}}
REFUSED = {{**SAMPLE, {refused}}}
"""

REFUSAL_TEST_TEMPLATE = '''

def test_it_refuses_a_capability_it_has_not_declared() -> None:
    """SAD 10.3 rule 4, and the refusal names the demand."""
    problems = driver.validate(sample_spec({block}=REFUSED))
    assert [problem.code for problem in problems] == ["unsupported-capability"]
    assert "{undeclared}" in problems[0].message
'''

#: The `spec` block each group's capabilities are read off, and the key within
#: it that carries them. The SAD 6.2 sample asks for three export formats, two
#: eval suites and LoRA at bf16, so a freshly scaffolded driver would otherwise
#: fail its own conformance run on the first line -- correct behaviour, and a
#: useless first experience.
_BLOCKS: Final[dict[str, tuple[str, str]]] = {
    "draupnir.export": ("release", "formats"),
    "draupnir.eval": ("evaluate", "suites"),
    "draupnir.train": ("train", "method"),
}

#: `capabilities_for("draupnir.train")` puts the specification's precision in
#: the demand alongside its method, so a train driver that declares no
#: precision can never be selected. These are the names the estate uses.
PRECISIONS: Final = frozenset({"bf16", "fp16", "fp32", "fp8", "int8", "nf4"})

UNDECLARED: Final = "no_such_capability"


def _overrides(group: str, capabilities: tuple[str, ...]) -> tuple[str, str, str]:
    """Return (block name, accepted block, refused block) for the generated test.

    A merge driver reads no capability off the specification, so the sample
    runs unmodified and there is nothing here for it to refuse.
    """
    if group not in _BLOCKS:
        return "", "", ""
    block, key = _BLOCKS[group]
    if group == "draupnir.train":
        precisions = [item for item in capabilities if item in PRECISIONS]
        methods = [item for item in capabilities if item not in PRECISIONS]
        if not precisions or not methods:
            msg = (
                "a train driver's demand is its method and its precision together "
                "(`RunSpec.capabilities_for`), so declare at least one of each, e.g. "
                "`--capability lora --capability bf16`. Known precisions: "
                f"{', '.join(sorted(PRECISIONS))}."
            )
            raise ScaffoldError(msg)
        precision = json.dumps(precisions[0])
        return (
            block,
            f'"{key}": {json.dumps(methods[0])}, "precision": {precision}',
            f'"{key}": {json.dumps(UNDECLARED)}, "precision": {precision}',
        )
    return (
        block,
        f'"{key}": {json.dumps(list(capabilities))}',
        f'"{key}": {json.dumps([UNDECLARED])}',
    )


def _insert_sorted(text: str, pattern: re.Pattern[str], line: str) -> str:
    """Insert `line` into the block `pattern` matches, preserving its order.

    Idempotent: a line already present is left where it is. A block that is
    already alphabetical stays alphabetical, and one that is in some deliberate
    order of its own -- the import contract lists its drivers roughly in the
    order they were built -- is appended to rather than rearranged. A scaffold
    that reorders a file it was asked to add one line to produces a diff nobody
    can review.
    """
    match = pattern.search(text)
    if match is None:
        msg = (
            "the root pyproject.toml has no block matching "
            f"{pattern.pattern!r}. Register the distribution by hand, or pass "
            "--no-register."
        )
        raise ScaffoldError(msg)
    body = match.group("body")
    existing = [entry for entry in body.splitlines() if entry.strip()]
    if any(entry.strip() == line.strip() for entry in existing):
        return text
    indent = existing[0][: len(existing[0]) - len(existing[0].lstrip())] if existing else ""
    entry = indent + line.strip()
    keys = [item.strip() for item in existing]
    merged = (
        sorted([*existing, entry], key=str.strip) if keys == sorted(keys) else [*existing, entry]
    )
    return text[: match.start("body")] + "\n".join(merged) + "\n" + text[match.end("body") :]


#: `[tool.uv.sources]` at the root, which is where a workspace member is
#: declared, and the isort first-party list, which is what makes the generated
#: conformance test's import land in the right block.
_UV_SOURCES = re.compile(
    r"(?m)^\[tool\.uv\.sources\]\n(?P<body>(?:^[a-z0-9-]+ = .*\n)+)", re.MULTILINE
)
_FIRST_PARTY = re.compile(r"(?m)^known-first-party = \[\n(?P<body>(?:^  \".*\",\n)+)\]")


#: The packages import-linter analyses, and the `source_modules` of the
#: contract that forbids a driver from importing the core. Both name every
#: driver rather than matching a pattern, so a driver missing from either is a
#: driver the contract does not check -- and nothing fails while it is missing,
#: which is what makes this worth automating.
_ROOT_PACKAGES = re.compile(r"(?m)^root_packages =\n(?P<body>(?:^ +\S+\n)+)")
_DRIVER_CONTRACT = re.compile(
    r"(?ms)^\[importlinter:contract:drivers-depend-on-interfaces-only\].*?"
    r"^source_modules =\n(?P<body>(?:^ +\S+\n)+)"
)


def register(pyproject: Path, importlinter: Path, distribution: str, module: str) -> list[Path]:
    """Declare the new driver where the toolchain has to be told about it.

    Four entries, all four of which every existing driver already has: the
    workspace source, so `uv sync` installs it; the isort first-party name, so
    the generated conformance test's import sorts where it belongs; and
    import-linter's `root_packages` and driver contract `source_modules`,
    because that contract lists its drivers by name.

    The first two are why the output lints without a manual edit, which is the
    claim this skill makes. The last two are the ones a person forgets, and
    forgetting them fails nothing: the contract quietly stops covering the
    newest driver, which is the shape of failure AC-N9 exists to prevent.
    """
    changed: list[Path] = []

    text = pyproject.read_text(encoding="utf-8")
    updated = _insert_sorted(text, _UV_SOURCES, f"{distribution} = {{ workspace = true }}")
    updated = _insert_sorted(updated, _FIRST_PARTY, f'"{module}",')
    if updated != text:
        pyproject.write_text(updated, encoding="utf-8", newline="\n")
        changed.append(pyproject)

    contracts = importlinter.read_text(encoding="utf-8")
    amended = _insert_sorted(contracts, _ROOT_PACKAGES, module)
    amended = _insert_sorted(amended, _DRIVER_CONTRACT, module)
    if amended != contracts:
        importlinter.write_text(amended, encoding="utf-8", newline="\n")
        changed.append(importlinter)

    return changed


def scaffold(
    *,
    group: str,
    name: str,
    distribution: str,
    capabilities: tuple[str, ...],
    out: Path,
    tests_out: Path,
    pyproject: Path | None = None,
    summary: str | None = None,
    executable: str | None = None,
    output: str = "output.bin",
    artefact_kind: str = "report",
    gpus: int = 0,
) -> list[Path]:
    """Write the distribution and its conformance run, returning every path."""
    if group not in GROUPS:
        msg = f"{group} is not an extension point. One of: {', '.join(sorted(GROUPS))}"
        raise ScaffoldError(msg)
    if group not in JOB_GROUPS:
        msg = (
            f"a {group} driver plans no job, so this scaffold does not fit it. It "
            "generates the shape `check_job_driver` checks, which covers "
            f"{', '.join(sorted(JOB_GROUPS))}."
        )
        raise ScaffoldError(msg)
    if not NAME_PATTERN.match(name):
        msg = (
            f"{name!r} is not a versioned interface name. The form is "
            "`namespace.implementation/vMAJOR`, e.g. `skidbladnir.zip/v1`: the major "
            "version lives in the name so two majors can be installed at once "
            "(SAD 10.3 rule 1)."
        )
        raise ScaffoldError(msg)
    if not DISTRIBUTION_PATTERN.match(distribution):
        msg = (
            f"{distribution!r} is not a distribution name. Use lowercase words joined "
            "by hyphens, e.g. `veldris-draupnir-zip-export`."
        )
        raise ScaffoldError(msg)
    if not capabilities:
        msg = (
            "a driver declares at least one capability. One that declares none can "
            "never be selected, because selection is by capability (SAD 10.3 rule 4)."
        )
        raise ScaffoldError(msg)
    if artefact_kind not in ARTEFACT_KINDS:
        msg = (
            f"{artefact_kind!r} is not an artefact kind. The schema knows "
            f"{', '.join(ARTEFACT_KINDS)}, and refuses a ninth at collection time."
        )
        raise ScaffoldError(msg)

    module = module_of(distribution)
    classname = class_of(name)
    protocol = GROUPS[group]
    summary = summary or f"{protocol} for DRAUPNIR: {', '.join(capabilities)}."
    executable = executable or module.replace("_", "-")
    block, accepted, refused = _overrides(group, capabilities)
    constants = (
        CONSTANTS_TEMPLATE.format(block=block, accepted=accepted, refused=refused) if block else ""
    )
    testing_import = (
        "from draupnir.interfaces.testing import (\n"
        "    SAMPLE_SPEC_MAPPING,\n"
        "    check_job_driver,\n"
        "    describe,\n"
        "    sample_spec,\n"
        ")\n"
        if block
        else "from draupnir.interfaces.testing import check_job_driver, describe, sample_spec\n"
    )
    accepted_call = f"{block}=ACCEPTED" if block else ""
    refusal_test = REFUSAL_TEST_TEMPLATE.format(block=block, undeclared=UNDECLARED) if block else ""

    test_path = tests_out / f"test_{module}.py"
    package = out / module
    package.mkdir(parents=True, exist_ok=True)
    tests_out.mkdir(parents=True, exist_ok=True)

    written: list[Path] = []

    def write(path: Path, text: str) -> None:
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(path)

    write(
        package / "__init__.py",
        DRIVER_TEMPLATE.format(
            summary=summary,
            name=name,
            group=group,
            capabilities=", ".join(f'"{item}"' for item in capabilities),
            classname=classname,
            executable=executable,
            output=output,
            artefact_kind=artefact_kind,
            gpus=gpus,
        ),
    )
    write(
        out / "pyproject.toml",
        PYPROJECT_TEMPLATE.format(
            distribution=distribution,
            summary=summary,
            group=group,
            name=name,
            module=module,
        ),
    )
    write(
        out / "README.md",
        README_TEMPLATE.format(
            distribution=distribution,
            summary=summary,
            protocol=protocol,
            group=group,
            capability_list=", ".join(f"`{item}`" for item in capabilities),
            test_path=test_path.as_posix(),
        ),
    )
    write(
        test_path,
        TEST_TEMPLATE.format(
            distribution=distribution,
            module=module,
            testing_import=testing_import,
            constants=constants,
            accepted_call=accepted_call,
            refusal_test=refusal_test,
        ),
    )

    if pyproject is not None:
        written.extend(
            register(pyproject, pyproject.parent / ".importlinter", distribution, module)
        )

    return written


def main(argv: list[str] | None = None) -> int:
    """Scaffold a driver from the command line."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--group", required=True, choices=sorted(GROUPS))
    parser.add_argument("--name", required=True, help="e.g. skidbladnir.zip/v1")
    parser.add_argument("--distribution", required=True, help="e.g. veldris-draupnir-zip-export")
    parser.add_argument(
        "--capability", action="append", required=True, dest="capabilities", metavar="CAP"
    )
    parser.add_argument("--out", type=Path, required=True, help="e.g. plugins/zip_export")
    parser.add_argument("--tests-out", type=Path, default=REPO_ROOT / "tests" / "contract")
    parser.add_argument(
        "--no-register",
        action="store_false",
        dest="register",
        help="do not touch the root pyproject.toml (for scaffolding outside the repo)",
    )
    parser.add_argument("--summary")
    parser.add_argument("--executable", help="defaults to the module name, hyphenated")
    parser.add_argument("--output", default="output.bin")
    parser.add_argument("--artefact-kind", default="report", choices=ARTEFACT_KINDS)
    parser.add_argument("--gpus", type=int, default=0)
    args = parser.parse_args(argv)

    try:
        written = scaffold(
            group=args.group,
            name=args.name,
            distribution=args.distribution,
            capabilities=tuple(args.capabilities),
            out=args.out,
            tests_out=args.tests_out,
            pyproject=(REPO_ROOT / "pyproject.toml") if args.register else None,
            summary=args.summary,
            executable=args.executable,
            output=args.output,
            artefact_kind=args.artefact_kind,
            gpus=args.gpus,
        )
    except ScaffoldError as error:
        parser.error(str(error))

    for path in written:
        print(f"wrote {path}")
    print("\nNext: `uv sync`, then `uv run pytest -m contract` to put it through the harness.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
